"""Starter project templates matching ADR 0002 v1.1 and RobotConfig v2."""

from __future__ import annotations

from pathlib import Path
from typing import Final

import yaml

from hiyelx.config.v2.models import (
    ComponentDefinition,
    RobotConfig,
    RobotMetadata,
    RuntimeSettings,
)
from hiyelx.core.types import ComponentCategory
from hiyelx.project.errors import ProjectTemplateError
from hiyelx.project.loader import (
    PROJECT_MANIFEST_FILENAME,
    atomic_write_text,
    load_studio_project,
    serialize_project_manifest_yaml,
    serialize_robot_config_yaml,
)
from hiyelx.project.models import (
    CanvasLayoutDocument,
    GraphEdge,
    GraphNode,
    LoadedStudioProject,
    NodePosition,
    ProfileDefinition,
    ProjectManifest,
    ProjectMetadata,
    ProjectRuntimeContract,
    RobotGraphDocument,
    StudioEdgeKind,
    StudioNodeKind,
    WorkspacePaths,
)
from hiyelx.resources import ResourceIdentity

STARTER_TEMPLATES: Final[tuple[str, ...]] = (
    "canonical-mock-rover",
    "single-sim-motor",
    "blank-robot",
)

_WORKSPACE_DIRS: Final[tuple[str, ...]] = (
    "robot/components",
    "robot/connections",
    "applications/tasks",
    "configs",
    "assets/meshes",
    "assets/models",
    "tests",
)


def create_studio_project(
    target_dir: str | Path,
    *,
    project_id: str,
    project_name: str,
    template: str = "canonical-mock-rover",
    description: str | None = None,
) -> LoadedStudioProject:
    """Create a validated HIYELX Studio workspace on disk from a built-in template."""
    if template not in STARTER_TEMPLATES:
        raise ProjectTemplateError(
            f"unknown project template {template!r}; expected one of {STARTER_TEMPLATES}"
        )
    if not project_id.strip() or not project_name.strip():
        raise ProjectTemplateError("project_id and project_name must not be blank")

    root = Path(target_dir)
    if root.exists():
        if not root.is_dir():
            raise ProjectTemplateError(f"target {root} exists and is not a directory")
        if any(root.iterdir()):
            raise ProjectTemplateError(f"target directory {root} is not empty")
    else:
        root.mkdir(parents=True, exist_ok=True)

    for rel_dir in _WORKSPACE_DIRS:
        (root / rel_dir).mkdir(parents=True, exist_ok=True)

    manifest = ProjectManifest(
        schema_version="1",
        project=ProjectMetadata(
            id=project_id,
            name=project_name,
            version="0.1.0",
            description=description or f"HIYELX Studio project ({template})",
            template=template,
        ),
        workspace=WorkspacePaths(),
        profiles={
            "sim": ProfileDefinition(
                description="Deterministic local simulation profile",
                overrides="configs/sim.yaml",
            ),
            "dev": ProfileDefinition(
                description="Local developer profile",
                overrides="configs/dev.yaml",
            ),
        },
        runtime=ProjectRuntimeContract(),
    )

    robot_config, graph, layout = _build_template_documents(
        template=template,
        project_id=project_id,
        project_name=project_name,
        description=manifest.project.description,
    )

    atomic_write_text(
        root,
        PROJECT_MANIFEST_FILENAME,
        serialize_project_manifest_yaml(manifest),
    )
    atomic_write_text(
        root,
        manifest.workspace.robot_config,
        serialize_robot_config_yaml(robot_config),
    )
    atomic_write_text(
        root,
        manifest.workspace.graph_file,
        yaml.safe_dump(
            graph.model_dump(mode="json", exclude_none=True),
            sort_keys=False,
            allow_unicode=True,
        ),
    )
    atomic_write_text(
        root,
        manifest.workspace.layout_file,
        yaml.safe_dump(
            layout.model_dump(mode="json"),
            sort_keys=False,
            allow_unicode=True,
        ),
    )
    atomic_write_text(
        root,
        "configs/sim.yaml",
        yaml.safe_dump({"profile": "sim", "runtime": {"tick_rate_hz": 50.0}}, sort_keys=False),
    )
    atomic_write_text(
        root,
        "configs/dev.yaml",
        yaml.safe_dump({"profile": "dev", "runtime": {"log_level": "DEBUG"}}, sort_keys=False),
    )
    atomic_write_text(
        root,
        "applications/main.yaml",
        yaml.safe_dump({"schema_version": "1", "tasks": []}, sort_keys=False),
    )
    atomic_write_text(
        root,
        "README.md",
        f"# {project_name}\n\nGenerated by HIYELX Studio (`{template}`).\n",
    )
    return load_studio_project(root)


def _build_template_documents(
    *,
    template: str,
    project_id: str,
    project_name: str,
    description: str | None,
) -> tuple[RobotConfig, RobotGraphDocument, CanvasLayoutDocument]:
    if template == "canonical-mock-rover":
        robot_config = RobotConfig(
            schema_version="2",
            robot=RobotMetadata(
                id=project_id,
                name=project_name,
                version="0.1.0",
                description=description,
            ),
            runtime=RuntimeSettings(tick_rate_hz=50.0, log_level="INFO", history_retention_days=7),
            components=[
                ComponentDefinition(
                    id=ResourceIdentity("wheel_encoder"),
                    category=ComponentCategory.FEEDBACK,
                    model="mock.encoder",
                    settings={"resolution": 4096},
                ),
                ComponentDefinition(
                    id=ResourceIdentity("drive_motor"),
                    category=ComponentCategory.ACTUATOR,
                    model="mock.motor",
                    depends_on=(ResourceIdentity("wheel_encoder"),),
                    settings={"max_rpm": 300.0},
                ),
                ComponentDefinition(
                    id=ResourceIdentity("base_imu"),
                    category=ComponentCategory.SPATIAL,
                    model="mock.imu",
                    depends_on=(ResourceIdentity("drive_motor"),),
                    settings={"sample_rate_hz": 100.0},
                ),
                ComponentDefinition(
                    id=ResourceIdentity("front_camera"),
                    category=ComponentCategory.VISION,
                    model="mock.camera",
                    depends_on=(ResourceIdentity("base_imu"),),
                    settings={"width": 640, "height": 480, "fps": 30},
                ),
            ],
        )
        graph = RobotGraphDocument(
            schema_version="1",
            nodes=(
                GraphNode(
                    id="wheel_encoder",
                    kind=StudioNodeKind.SENSOR,
                    label="Wheel Encoder",
                    component_id="wheel_encoder",
                    category=ComponentCategory.FEEDBACK,
                    model="mock.encoder",
                ),
                GraphNode(
                    id="motion_controller",
                    kind=StudioNodeKind.CONTROLLER,
                    label="Motion Controller",
                ),
                GraphNode(
                    id="drive_motor",
                    kind=StudioNodeKind.ACTUATOR,
                    label="Drive Motor",
                    component_id="drive_motor",
                    category=ComponentCategory.ACTUATOR,
                    model="mock.motor",
                ),
                GraphNode(
                    id="base_imu",
                    kind=StudioNodeKind.SENSOR,
                    label="Base IMU",
                    component_id="base_imu",
                    category=ComponentCategory.SPATIAL,
                    model="mock.imu",
                ),
                GraphNode(
                    id="front_camera",
                    kind=StudioNodeKind.SENSOR,
                    label="Front Camera",
                    component_id="front_camera",
                    category=ComponentCategory.VISION,
                    model="mock.camera",
                ),
            ),
            edges=(
                # Acyclic lifecycle dependencies matching robot.yaml depends_on
                GraphEdge(
                    id="dep-enc-motor",
                    source="wheel_encoder",
                    target="drive_motor",
                    kind=StudioEdgeKind.DEPENDENCY,
                ),
                GraphEdge(
                    id="dep-motor-imu",
                    source="drive_motor",
                    target="base_imu",
                    kind=StudioEdgeKind.DEPENDENCY,
                ),
                GraphEdge(
                    id="dep-imu-cam",
                    source="base_imu",
                    target="front_camera",
                    kind=StudioEdgeKind.DEPENDENCY,
                ),
                # Closed-loop control cycle (allowed in general graph, excluded from depends_on)
                GraphEdge(
                    id="data-enc-ctrl",
                    source="wheel_encoder",
                    target="motion_controller",
                    kind=StudioEdgeKind.DATA,
                    topic="encoder/ticks",
                ),
                GraphEdge(
                    id="cmd-ctrl-motor",
                    source="motion_controller",
                    target="drive_motor",
                    kind=StudioEdgeKind.COMMAND,
                    topic="motor/velocity_cmd",
                ),
                GraphEdge(
                    id="fb-motor-ctrl",
                    source="drive_motor",
                    target="motion_controller",
                    kind=StudioEdgeKind.FEEDBACK,
                    topic="motor/state",
                ),
            ),
        )
        layout = CanvasLayoutDocument(
            schema_version="1",
            positions={
                "wheel_encoder": NodePosition(x=80.0, y=140.0),
                "motion_controller": NodePosition(x=340.0, y=140.0),
                "drive_motor": NodePosition(x=600.0, y=140.0),
                "base_imu": NodePosition(x=340.0, y=320.0),
                "front_camera": NodePosition(x=600.0, y=320.0),
            },
        )
        return robot_config, graph, layout

    if template == "single-sim-motor":
        robot_config = RobotConfig(
            schema_version="2",
            robot=RobotMetadata(
                id=project_id,
                name=project_name,
                version="0.1.0",
                description=description,
            ),
            runtime=RuntimeSettings(tick_rate_hz=50.0, log_level="INFO", history_retention_days=7),
            components=[
                ComponentDefinition(
                    id=ResourceIdentity("sim_motor"),
                    category=ComponentCategory.ACTUATOR,
                    model="mock.motor",
                    settings={"max_rpm": 300.0},
                )
            ],
        )
        graph = RobotGraphDocument(
            schema_version="1",
            nodes=(
                GraphNode(
                    id="sim_motor",
                    kind=StudioNodeKind.ACTUATOR,
                    label="Simulated Motor",
                    component_id="sim_motor",
                    category=ComponentCategory.ACTUATOR,
                    model="mock.motor",
                ),
            ),
            edges=(),
        )
        layout = CanvasLayoutDocument(
            schema_version="1",
            positions={"sim_motor": NodePosition(x=240.0, y=180.0)},
        )
        return robot_config, graph, layout

    # blank-robot
    robot_config = RobotConfig(
        schema_version="2",
        robot=RobotMetadata(
            id=project_id,
            name=project_name,
            version="0.1.0",
            description=description,
        ),
        runtime=RuntimeSettings(),
        components=[],
    )
    graph = RobotGraphDocument(schema_version="1", nodes=(), edges=())
    layout = CanvasLayoutDocument(schema_version="1", positions={})
    return robot_config, graph, layout
