from math import isclose, pi

from hiyelx.drivers.dynamixel.constants import (
    EXPECTED_MODEL_NUMBER,
    GOAL_VELOCITY_ADDRESS,
    GOAL_VELOCITY_SIZE,
    HARDWARE_ERROR_STATUS_ADDRESS,
    HARDWARE_ERROR_STATUS_SIZE,
    MODEL_NUMBER_ADDRESS,
    MODEL_NUMBER_SIZE,
    OPERATING_MODE_ADDRESS,
    OPERATING_MODE_SIZE,
    POSITION_UNIT_RADIANS,
    PRESENT_POSITION_ADDRESS,
    PRESENT_POSITION_SIZE,
    PRESENT_VELOCITY_ADDRESS,
    PRESENT_VELOCITY_SIZE,
    PROTOCOL_VERSION,
    TORQUE_ENABLE_ADDRESS,
    TORQUE_ENABLE_SIZE,
    VELOCITY_CONTROL_MODE,
    VELOCITY_UNIT_RADIANS_PER_SECOND,
)


def test_fixed_xl430_control_table_contract() -> None:
    assert PROTOCOL_VERSION == 2.0
    assert EXPECTED_MODEL_NUMBER == 1060
    assert (MODEL_NUMBER_ADDRESS, MODEL_NUMBER_SIZE) == (0, 2)
    assert (OPERATING_MODE_ADDRESS, OPERATING_MODE_SIZE) == (11, 1)
    assert (TORQUE_ENABLE_ADDRESS, TORQUE_ENABLE_SIZE) == (64, 1)
    assert (HARDWARE_ERROR_STATUS_ADDRESS, HARDWARE_ERROR_STATUS_SIZE) == (70, 1)
    assert (GOAL_VELOCITY_ADDRESS, GOAL_VELOCITY_SIZE) == (104, 4)
    assert (PRESENT_VELOCITY_ADDRESS, PRESENT_VELOCITY_SIZE) == (128, 4)
    assert (PRESENT_POSITION_ADDRESS, PRESENT_POSITION_SIZE) == (132, 4)
    assert VELOCITY_CONTROL_MODE == 1


def test_fixed_xl430_si_unit_conversions() -> None:
    assert isclose(VELOCITY_UNIT_RADIANS_PER_SECOND, 0.229 * 2 * pi / 60)
    assert isclose(POSITION_UNIT_RADIANS, 0.088 * pi / 180)
